import {expect,test} from '@playwright/test'
import {challengeOne,readDatabase,seedCards} from './support/cardFixture'
import type {BlindOption} from '../src/services/blindRewards'
for(const zonk of [true,false]) test(`rank 5 chooses one closed card and persists the result (Zonk=${zonk})`,async({page,context})=>{
 await seedCards(page,challengeOne)
 await page.goto(`/admin/scoreboard/${challengeOne}`)
 await page.getByRole('button',{name:'Draw Bonus Cards',exact:true}).click()
 await expect(page.getByText('Bonus cards already drawn for this challenge.',{exact:false})).toBeVisible()
 const db=await readDatabase(page)
 const raw=db.exec('SELECT options FROM blind_reward')[0].values[0][0]
 const options=JSON.parse(String(raw)) as BlindOption[]
 const chosenIndex=options.findIndex((option)=>!!option.zonk===zonk)
 db.close()
 const projector=await context.newPage();await projector.goto(`/rewards/${challengeOne}`)
 const draw=projector.getByLabel('Rank 5 blind draw Pink',{exact:true})
 await expect(draw.getByAltText('Kartu tertutup',{exact:true})).toHaveCount(3)
 await expect(draw.getByAltText('False Hope',{exact:true})).toHaveCount(0)
 await draw.getByRole('button').nth(chosenIndex).click()
 await expect(draw.locator('.is-open')).toHaveCount(1)
 await expect(draw.getByAltText('Kartu tertutup',{exact:true})).toHaveCount(2)
 if(zonk) await expect(draw.getByAltText('False Hope',{exact:true})).toBeVisible()
 else await expect(draw.locator('.is-open .card-art')).toBeVisible()
 await projector.reload()
 await expect(draw.locator('.is-open')).toHaveCount(1)
 for(const button of await draw.getByRole('button').all()) await expect(button).toBeDisabled()
 await projector.setViewportSize({width:1280,height:720})
 await projector.screenshot({path:`test-results/rank5-${zonk?'zonk':'normal'}-public.png`,animations:'disabled'})
 const saved=await readDatabase(projector)
 expect(Number(saved.exec("SELECT COUNT(*) FROM team_card WHERE team=(SELECT id FROM team WHERE name='Pink')")[0].values[0][0])).toBe(zonk?0:1)
 saved.close()
})
test('Card Reveal applies GP once, locks passive Second Chance, then revives only after damage',async({page,context})=>{
 await seedCards(page,challengeOne,[['Biru','Normal Heal Card #01'],['Biru','Rare Thief Card #01'],['Hijau','Legendary Second Chance Card']],true)
 await expect(page.getByRole('button',{name:'Select Legendary Second Chance Card for Hijau',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'Select Normal Heal Card #01 for Biru',exact:true}).click()
 await expect(page.getByRole('button',{name:'Select Normal Heal Card #01 for Biru',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Select Rare Thief Card #01 for Biru',exact:true}).click()
 await page.getByRole('button',{name:'Assign Rare Thief Card #01 owned by Biru to Hijau',exact:true}).click()
 await page.getByRole('button',{name:'Card Reveal',exact:true}).click()
 const projector=await context.newPage();await projector.goto(`/card-reveal/${challengeOne}`)
 const blue=projector.locator('.tactical-stage__team').filter({hasText:'Tim Biru'})
 const green=projector.locator('.tactical-stage__team').filter({hasText:'Tim Hijau'})
 await expect(blue.locator('.tactical-stage__gp')).toHaveText('11 GP')
 await expect(green.locator('.tactical-stage__gp')).toHaveText('0 GP')
 await page.getByRole('button',{name:'Show Card Reveal',exact:true}).click()
 await projector.reload()
 await expect(blue.locator('.tactical-stage__gp')).toHaveText('11 GP')
 await page.getByRole('button',{name:'Serang semua tim −2 GP',exact:true}).click()
 await expect(page.getByRole('button',{name:'Serangan selesai',exact:true})).toBeDisabled()
 await expect(blue.locator('.tactical-stage__gp')).toHaveText('9 GP')
 await expect(green.locator('.tactical-stage__gp')).toHaveText('1 GP')
})

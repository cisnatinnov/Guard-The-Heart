import {expect,test} from '@playwright/test'
import {challengeOne,readDatabase,seedCards} from './support/cardFixture'
import type {BlindOption} from '../src/services/blindRewards'
import {expectRewardContentsWithinFrame} from './support/layoutBounds'
for(const chosenIndex of [0,2]) test(`admin chooses an open rank 5 card and public mirrors cursor and result (option=${chosenIndex+1})`,async({page,context})=>{
 await seedCards(page,challengeOne)
 await page.goto(`/admin/scoreboard/${challengeOne}`)
 await page.getByRole('button',{name:'Draw Bonus Cards',exact:true}).click()
 await expect(page.getByText('Bonus cards already drawn for this challenge.',{exact:false})).toBeVisible()
 const db=await readDatabase(page)
 const raw=db.exec('SELECT options FROM blind_reward')[0].values[0][0]
 const options=JSON.parse(String(raw)) as BlindOption[]
 expect(options).toHaveLength(3)
 expect(options.every((option)=>!option.zonk)).toBe(true)
 db.close()
 const projector=await context.newPage();await projector.goto(`/rewards/${challengeOne}`)
 const draw=projector.getByLabel('Rank 5 blind draw Pink',{exact:true})
 await expect(draw.getByAltText('Closed card',{exact:true})).toHaveCount(3)
 await expectRewardContentsWithinFrame(projector)
 await expect(draw.getByAltText('False Hope',{exact:true})).toHaveCount(0)
 for (const button of await draw.getByRole('button').all()) await expect(button).toBeDisabled()
 await page.goto(`/admin/rewards/${challengeOne}`)
 const adminDraw=page.getByLabel('Rank 5 blind draw Pink',{exact:true})
 await expect(adminDraw.getByAltText('Closed card',{exact:true})).toHaveCount(0)
 await expect(adminDraw.locator('.card-art')).toHaveCount(3)
 await expect(adminDraw.getByRole('button').first()).toHaveCSS('cursor','pointer')
 await expect(draw.getByRole('button').first()).toHaveCSS('cursor','pointer')
 await adminDraw.getByRole('button').nth(chosenIndex).hover()
 await expect(draw.getByRole('img',{name:'Admin cursor · highlighting a card',exact:true})).toBeVisible()
 await expect(draw.locator('.is-pointed')).toHaveCount(1)
 await expect(draw.getByRole('button').nth(chosenIndex)).toHaveClass(/is-pointed/)
 await expectRewardContentsWithinFrame(projector)
 await expectRewardContentsWithinFrame(page)
 await expect(draw.getByAltText('Closed card',{exact:true})).toHaveCount(3)
 await page.mouse.move(0,0)
 await expect(draw.locator('.reward-pointer')).toHaveCount(0)
 await adminDraw.getByRole('button').nth(chosenIndex).focus()
 await expect(draw.getByRole('img',{name:'Admin cursor · highlighting a card',exact:true})).toBeVisible()
 await adminDraw.getByRole('button').nth(chosenIndex).click()
 await expect(draw.locator('.reward-pointer')).toHaveCount(0)
 await expect(draw.locator('.is-open')).toHaveCount(1)
 for (const cards of [draw,adminDraw]) for (const button of await cards.getByRole('button').all()) await expect(button).toHaveCSS('cursor','not-allowed')
 await expect(draw.getByAltText('Closed card',{exact:true})).toHaveCount(2)
 await expect(draw.locator('.is-open .card-art')).toBeVisible()
 await projector.reload()
 await expect(draw.locator('.is-open')).toHaveCount(1)
 await expect(draw.locator('.reward-pointer')).toHaveCount(0)
 for(const button of await draw.getByRole('button').all()) {
  await expect(button).toBeDisabled()
  await expect(button).toHaveCSS('cursor','not-allowed')
 }
 await projector.setViewportSize({width:1280,height:720})
 for (const width of [390,768,1280,1366,1920]) {
  const height=width===1366?600:Math.round(width*9/16)
  await projector.setViewportSize({width,height})
  await page.setViewportSize({width,height})
  await expectRewardContentsWithinFrame(projector)
  await expectRewardContentsWithinFrame(page)
  expect(await projector.locator('.reward-stage__row').evaluateAll((rows)=>rows.every((row)=>{
   const region=row.getBoundingClientRect()
   const cells=[...row.querySelectorAll('.reward-stage__identity,.reward-stage__earned')].map((cell)=>cell.getBoundingClientRect())
   return cells.every((cell,index)=>cell.top>=region.top && cell.bottom<=region.bottom && (index===0 || cell.left>=cells[index-1].right))
  }))).toBe(true)
 }
 await projector.setViewportSize({width:1280,height:720})
 await projector.screenshot({path:`test-results/rank5-${chosenIndex}-public.png`,animations:'disabled'})
 const saved=await readDatabase(projector)
 expect(Number(saved.exec("SELECT COUNT(*) FROM team_card WHERE team=(SELECT id FROM team WHERE name='Pink')")[0].values[0][0])).toBe(1)
 saved.close()
})
test('Card Reveal applies GP once, locks passive Second Chance, then revives only after damage',async({page,context})=>{
 await seedCards(page,challengeOne,[['Biru','Normal Heal Card #01'],['Biru','Rare Thief Card #01'],['Hijau','Legendary Second Chance Card']],true)
 await expect(page.getByRole('button',{name:'Select Legendary Second Chance Card for Hijau',exact:true})).toBeDisabled()
 await page.getByRole('button',{name:'Select Normal Heal Card #01 for Biru',exact:true}).click()
 await expect(page.getByRole('button',{name:'Select Normal Heal Card #01 for Biru',exact:true})).toHaveAttribute('aria-pressed','true')
 await page.getByRole('button',{name:'Select Rare Thief Card #01 for Biru',exact:true}).click()
 await page.getByRole('button',{name:'Assign Rare Thief Card #01 owned by Biru to Hijau',exact:true}).click()
 await page.getByRole('button',{name:'Card Reveal',exact:true}).click()
 const projector=await context.newPage();await projector.goto(`/card-reveal/${challengeOne}`)
 const blue=projector.locator('.tactical-stage__team').filter({hasText:'Team Biru'})
 const green=projector.locator('.tactical-stage__team').filter({hasText:'Team Hijau'})
 await expect(blue.locator('.tactical-stage__gp')).toHaveText('11 GP')
 await expect(green.locator('.tactical-stage__gp')).toHaveText('0 GP')
 await page.getByRole('button',{name:'Show Card Reveal',exact:true}).click()
 await projector.reload()
 await expect(blue.locator('.tactical-stage__gp')).toHaveText('11 GP')
 await page.getByRole('button',{name:'Attack all teams −2 GP',exact:true}).click()
 await expect(page.getByRole('button',{name:'Attack complete',exact:true})).toBeDisabled()
 await expect(blue.locator('.tactical-stage__gp')).toHaveText('9 GP')
 await expect(green.locator('.tactical-stage__gp')).toHaveText('1 GP')
})

import { test, expect } from '@playwright/test'
const decode = '/admin/play/emoji-decode/9f1c3a52-0d64-4e2b-8a71-5c0e2b7d4a10'
const matching = '/admin/play/word-assembly/7c4a2f96-08db-4e15-b3c7-1d9e5a80f463'

test('selected Image Decode questions sync to projector and survive reload', async ({ page, context }) => {
  await page.goto(decode)
  await expect(page.getByText('Play solo instead', { exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Main Presentation', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Turn Order', exact: true })).toBeVisible()
  await page.getByText('Choose questions · 10/10 selected').click()
  const picker = page.locator('.question-picker')
  await expect(picker.getByRole('checkbox').nth(10)).toBeDisabled()
  await picker.getByRole('button', { name: 'Clear selection' }).click()
  await picker.getByRole('checkbox').nth(1).check()
  await picker.getByRole('checkbox').nth(10).check()
  await page.getByRole('checkbox', { name: 'Kuning', exact: true }).check()
  await page.getByRole('button', { name: 'Start team run (1)', exact: true }).click()
  await expect(page.locator('.run-panel__title')).toContainText('question 1 of 2')
  await expect(page.getByRole('button', { name: /Right Answer|Wrong Answer/ })).toHaveCount(0)
  const clue = await page.locator('.workbook-emoji-clue').textContent()
  const publicPage = await context.newPage()
  await publicPage.goto(decode.replace('/admin', ''))
  await expect(publicPage.locator('.workbook-emoji-clue')).toHaveText(clue!)
  await page.reload()
  await expect(page.locator('.workbook-emoji-clue')).toHaveText(clue!)
  await page.screenshot({ path: '.validation.tmp/selected-decode-dark.png', fullPage: true })
  await page.getByRole('textbox', { name: 'Kuning answer', exact: true }).fill('SLIK')
  await page.getByRole('button', { name: 'Grade this question', exact: true }).click()
  await expect(page.locator('.run-panel__title')).toContainText('question 2 of 2')
})

test('workbook question selection, automatic grading and mobile themes', async ({ page }) => {
  await page.goto(matching)
  await expect(page.getByRole('region', { name: 'Challenge turn order' })).toBeVisible()
  await page.getByText('Choose questions · 10/10 selected').click()
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await expect(page.getByText('Choose at least one question to play.')).toBeVisible()
  await page.locator('.question-picker input').nth(1).check()
  await expect(page.locator('.workbook-quiz__eyebrow')).toContainText('Question 1 / 1')
  await page.getByRole('button', { name: 'Next question', exact: true }).isDisabled().then((disabled) => expect(disabled).toBe(true))
  await expect(page.getByRole('button', { name: /Right Answer|Wrong Answer/ })).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Team answer', exact: true }).selectOption({ index: 1 })
  await page.getByRole('button', { name: 'Submit answer', exact: true }).click()
  await expect(page.locator('.challenge-answer-controls')).toHaveAttribute('aria-busy', 'false')
  await expect(page.locator('.challenge-answer-controls')).toContainText('Kuning: -10')
  for (const width of [1440, 390]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `.validation.tmp/quiz-dark-${width}.png`, fullPage: true })
  }
  await page.getByRole('button', { name: 'Dark theme', exact: true }).click()
  await page.screenshot({ path: '.validation.tmp/quiz-light-mobile.png', fullPage: true })
})

test('Jaw of Risk grades the chosen option and unlocks the opponent tooth turn', async ({ page }) => {
  await page.goto('/admin/play/jaws-of-risk/d5e8b317-4c62-49af-8b03-2f7c19a6d5e8')
  await expect(page.getByRole('region', { name: 'Challenge turn order' })).toBeVisible()
  await page.getByRole('combobox', { name: 'Opponent to press', exact: true }).selectOption({ index: 1 })
  await page.getByRole('combobox', { name: 'Team answer', exact: true }).selectOption({ index: 2 })
  await page.getByRole('button', { name: 'Submit answer', exact: true }).click()
  await expect(page.locator('.challenge-answer-controls')).toContainText('Kuning: 10')
  await expect(page.getByRole('button', { name: 'Tooth 1', exact: true })).toBeEnabled()
  await expect(page.getByRole('button', { name: 'Next question', exact: true })).toBeDisabled()
  await page.screenshot({ path: '.validation.tmp/jaw-graded.png', fullPage: true })
})

import {expect,test} from '@playwright/test'
import {challengeOne,seedCards} from './support/cardFixture'

for (const [challengeId,count] of [[challengeOne,3],['d5e8b317-4c62-49af-8b03-2f7c19a6d5e8',4]] as const) test(`Fortune Draw shows ${count} closed options and grants one public choice`,async({page,context})=>{
 await seedCards(page,challengeId,[['Biru','Rare Fortune Draw Card #01']])
 await page.getByRole('button',{name:'Select Rare Fortune Draw Card #01 for Biru',exact:true}).click()
 const offers=page.locator('.fortune-choices button[aria-pressed]')
 await expect(offers).toHaveCount(count)
 await expect(offers.locator('img')).toHaveCount(count)
 await expect(offers.locator('img[src*="0_BACK"]')).toHaveCount(0)
 await page.getByRole('button',{name:'Card Reveal',exact:true}).click()
 const projector=await context.newPage();await projector.goto(`/card-reveal/${challengeId}`)
 const panel=projector.getByRole('complementary',{name:'Fortune Draw · Biru',exact:true})
 await expect(panel.locator('.fortune-reveal__option')).toHaveCount(count)
 await expect(panel.getByAltText('Closed card',{exact:true})).toHaveCount(count)
 const mode=page.getByRole('checkbox',{name:'Public view: closed cards',exact:true})
 await mode.click()
 await expect(mode).not.toBeChecked()
 await expect(panel.getByAltText('Closed card',{exact:true})).toHaveCount(0)
 await expect(panel.locator('.fortune-reveal__option img')).toHaveCount(count)
 await projector.reload()
 await expect(panel.getByAltText('Closed card',{exact:true})).toHaveCount(0)
 await page.reload()
 await expect(mode).not.toBeChecked()
 await projector.screenshot({path:`test-results/fortune-${count}-open-public.png`,animations:'disabled'})
 await page.locator('.giga-card-actions').screenshot({path:`test-results/fortune-${count}-open-admin.png`})
 await mode.click()
 await expect(mode).toBeChecked()
 await expect(panel.getByAltText('Closed card',{exact:true})).toHaveCount(count)
 await panel.getByRole('button',{name:'Choose closed card 1',exact:true}).click()
 await expect(panel.locator('.is-selected')).toHaveCount(1)
 await expect(panel.getByAltText('Closed card',{exact:true})).toHaveCount(count-1)
 await expect(offers.nth(0)).toHaveAttribute('aria-pressed','true')
 for (const button of await offers.all()) await expect(button).toBeDisabled()
 const selected=await panel.locator('.is-selected img').getAttribute('src')
 await projector.reload()
 await expect(panel.locator('.is-selected img')).toHaveAttribute('src',selected!)
 await page.reload()
 await expect(offers.nth(0)).toHaveAttribute('aria-pressed','true')
 await projector.setViewportSize({width:1280,height:720})
 await projector.screenshot({path:`test-results/fortune-${count}-closed-public.png`,animations:'disabled'})
 await page.getByRole('button',{name:'Serang semua tim −2 GP',exact:true}).click()
 await expect(page.getByRole('button',{name:'Serangan selesai',exact:true})).toBeDisabled()
 await expect(projector.locator('.tactical-stage__team').filter({hasText:'Tim Biru'}).locator('.tactical-stage__gp')).toHaveText('6 GP')
})

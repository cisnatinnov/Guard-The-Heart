test('Image Decode Timer starts on click without restarting the question or score', async ({ page, context }) => {
  await page.goto(decode)
  await expect(page.locator('.decode-stage__answer input')).toBeVisible()
  await expect(page.locator('.run-panel__answers table')).toHaveCount(0)
  await page.clock.install()
  const projector = await context.newPage()
  await projector.goto(decode.replace('/admin', ''))
  await page.clock.runFor(20000)
  await expect(page.locator('.decode-stage__timer strong')).toHaveText('15s')
  await expect(page.getByRole('button', { name: 'Restart challenge', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Timer', exact: true }).click()
  await page.clock.runFor(5000)
  await expect(page.locator('.decode-stage__timer strong')).toHaveText('10s')
  await projector.clock.install({ time: await page.evaluate(() => Date.now()) })
  await expect(projector.locator('.decode-stage__timer strong')).toHaveText('10s')
  await page.getByRole('textbox', { name: 'Kuning answer', exact: true }).fill('Selisih Kas')
  await page.getByRole('button', { name: 'Grade this question', exact: true }).click()
  await expect(page.locator('.run-panel__title')).toContainText('question 2 of 10')
  await expect(page.locator('.decode-stage__timer strong')).toHaveText('15s')
  await page.clock.runFor(20000)
  await expect(page.locator('.decode-stage__timer strong')).toHaveText('15s')
  await page.getByRole('button', { name: 'Timer', exact: true }).click()
  await expect(page.locator('.run-panel__title')).toContainText('question 2 of 10')
  await expect(page.locator('.decode-stage__answer input')).toBeEnabled()
})


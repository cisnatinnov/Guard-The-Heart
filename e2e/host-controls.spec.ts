test('the public dragon waits for Show dragon and follows hide/reload controls', async ({ page, context }) => {
  await page.goto(jaw)
  const projector = await context.newPage()
  await projector.goto(jaw.replace('/admin', ''))
  await expect(projector.locator('.workbook-quiz')).toBeVisible()
  await expect(projector.locator('.crocodile-stage')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show dragon', exact: true }).click()
  await expect(projector).toHaveURL(`${jaw.replace('/admin', '')}/dragon`)
  await expect(projector.locator('.workbook-quiz')).toHaveCount(0)
  await expect(projector.locator('.crocodile-stage')).toBeVisible()
  await projector.reload()
  await expect(projector.locator('.crocodile-stage')).toBeVisible()
  await page.getByRole('button', { name: 'Show public question', exact: true }).click()
  await expect(projector.locator('.workbook-quiz')).toBeVisible()
  await expect(projector.locator('.crocodile-stage')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show dragon', exact: true }).click()
  await expect(projector.locator('.crocodile-stage')).toBeVisible()
  await page.getByRole('button', { name: 'Hide dragon', exact: true }).click()
  await expect(projector).toHaveURL(jaw.replace('/admin', ''))
  await expect(projector.locator('.crocodile-stage')).toHaveCount(0)
  await expect(projector.locator('.workbook-quiz')).toBeVisible()
})

test('Matching Cards remains hidden until Show cards, which starts its full preview', async ({ page, context }) => {
  await page.goto(matching)
  await expect(page.getByRole('heading', { name: 'Challenge 2 - Matching Cards', exact: true })).toBeVisible()
  const projector = await context.newPage()
  await projector.goto(matching.replace('/admin', ''))
  const now = new Date()
  await page.clock.install({ time: now })
  await page.clock.pauseAt(new Date(now.getTime() + 1000))
  expect(await projector.evaluate(() => Date.now())).toBe(await page.evaluate(() => Date.now()))
  await expect(projector.locator('.flipping-presentation')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Show cards', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: /Tolak \(Deny\)/ }).click()
  await page.clock.runFor(30000)
  await expect(projector.locator('.flipping-presentation')).toHaveCount(0)
  await page.getByRole('button', { name: 'Grade this question', exact: true }).click()
  await page.getByRole('button', { name: 'Show cards', exact: true }).click()
  await expect(projector).toHaveURL(`${matching.replace('/admin', '')}/cards`)
  await expect(projector.locator('.workbook-quiz')).toHaveCount(0)
  await expect(projector.locator('.tile--revealed')).toHaveCount(20)
  await page.clock.runFor(4999)
  await expect(page.locator('.tile--revealed')).toHaveCount(20)
  await page.clock.runFor(1)
  await expect(page.locator('.tile--revealed')).toHaveCount(0)
  expect((await projector.locator('.tile').first().boundingBox())!.height).toBeGreaterThan(40)
  await projector.locator('.tile[data-pair="word-1"]').nth(0).click()
  await projector.locator('.tile[data-pair="word-1"]').nth(1).click()
  await expect(page.locator('.tile--matched')).toHaveCount(2)
  await page.getByRole('button', { name: 'Hide cards', exact: true }).click()
  await expect(projector).toHaveURL(matching.replace('/admin', ''))
  await expect(projector.locator('.workbook-quiz')).toBeVisible()
  await expect(projector.locator('.flipping-presentation')).toHaveCount(0)
  await page.getByRole('button', { name: 'Show cards', exact: true }).click()
  await expect(projector.locator('.tile--matched')).toHaveCount(2)
  await expect(projector.locator('.tile--revealed:not(.tile--matched)')).toHaveCount(0)
  await expect(projector.getByRole('timer')).toHaveCount(0)
})

import { expect, test } from '@playwright/test'

const decode = '/admin/play/emoji-decode/9f1c3a52-0d64-4e2b-8a71-5c0e2b7d4a10'
const matching = '/admin/play/word-assembly/7c4a2f96-08db-4e15-b3c7-1d9e5a80f463'
const jaw = '/admin/play/jaws-of-risk/d5e8b317-4c62-49af-8b03-2f7c19a6d5e8'

test('Challenge 1 opens a synchronized public question from admin', async ({ page }) => {
  await page.goto(decode)
  await expect(page.locator('.decode-stage__answer input')).toBeVisible()
  await expect(page.locator('.run-panel__answers table')).toHaveCount(0)
  const popup = page.waitForEvent('popup')
  await page.getByRole('button', { name: 'Show public question', exact: true }).click()
  const projector = await popup
  await expect(projector).toHaveURL(decode.replace('/admin', ''))
  await expect(projector.locator('.decode-stage')).toBeVisible()
  await expect(projector.getByRole('button', { name: 'Grade this question', exact: true })).toHaveCount(0)
  await page.getByRole('textbox', { name: 'Kuning answer', exact: true }).fill('Selisih Kas')
  await expect(projector.locator('.decode-stage__answer p')).toHaveText('Selisih Kas')
  await projector.reload()
  await expect(projector.locator('.decode-stage__answer p')).toHaveText('Selisih Kas')
  await page.getByRole('textbox', { name: 'Kuning answer', exact: true }).fill('')
  await expect(projector.locator('.decode-stage__answer p')).toContainText('Waiting for an answer')
  await page.getByRole('textbox', { name: 'Kuning answer', exact: true }).fill('Selisih Kas')
  await page.getByRole('textbox', { name: 'Kuning answer', exact: true }).press('Enter')
  await expect(projector.locator('.decode-stage')).toContainText('Question 2 / 10')
  await expect(projector.locator('.decode-stage__answer p')).not.toHaveText('Selisih Kas')
})

test('Image Decode mirrors a passed opponent answer and clears it on team changes', async ({ page, context }) => {
  await page.goto(decode)
  await expect(page.locator('.decode-stage__answer input')).toBeVisible()
  await expect(page.locator('.run-panel__answers table')).toHaveCount(0)
  const projector = await context.newPage()
  await projector.goto(decode.replace('/admin', ''))
  await page.getByRole('radio', { name: 'Pass to an opponent', exact: true }).check()
  await page.getByRole('combobox', { name: 'Opponent team', exact: true }).selectOption({ label: 'Merah' })
  await page.getByRole('textbox', { name: 'Merah answer', exact: true }).fill('Opponent draft')
  await expect(projector.locator('.decode-stage__answer p')).toHaveText('Opponent draft')
  await page.getByRole('region', { name: 'Challenge turn order', exact: true }).getByRole('button', { name: /Biru/ }).click()
  await expect(projector.locator('.decode-stage__answer p')).toContainText('Waiting for an answer from Biru')
  await page.getByRole('textbox', { name: 'Biru answer', exact: true }).fill('New team answer')
  await expect(projector.locator('.decode-stage__answer p')).toHaveText('New team answer')
})


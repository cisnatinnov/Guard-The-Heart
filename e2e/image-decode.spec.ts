import { expect, test } from '@playwright/test'

test('Image Decode advances after a wrong answer and after time runs out', async ({ page }) => {
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'Teams' })).toBeVisible({ timeout: 30_000 })

  await page.clock.install()
  await page.getByRole('navigation', { name: 'Admin views' }).getByRole('link', { name: 'Challenges', exact: true }).click()
  await page.locator('.card--locked', { hasText: 'Image Decode' }).getByRole('button', { name: 'Play' }).click()

  await page.getByText('Play solo instead', { exact: true }).click()
  const score = page.locator('.stat', { has: page.locator('.stat__label', { hasText: /^Score$/ }) }).locator('.stat__value')
  await expect(score).toHaveText('0/110')
  const answerInput = page.getByRole('textbox', { name: 'Decoded answer' })
  await answerInput.fill('not the answer')
  await page.getByRole('button', { name: 'Decode', exact: true }).click()
  await expect(page.locator('.alert--error')).toContainText('Not this time')
  await expect(score).toHaveText('-10/110')

  await expect(page.locator('.qa-stage__answer')).toContainText('Rekening')
  await expect(page.locator('.qa-stage__heading span')).toBeHidden()
  await expect(page.locator('.qa-stage__timer strong')).toBeVisible()
  await expect(page.locator('.qa-stage__timer strong')).toHaveText('15s')
  await expect(page.getByRole('timer', { name: /seconds remaining/ })).toBeVisible()
  await page.screenshot({ path: 'test-results/image-decode-question.png', fullPage: true })
  await page.getByRole('button', { name: 'Next →' }).click()
  await expect(page.locator('.qa-stage__hint')).toHaveText('1 Kata')
  await expect(page.locator('.qa-stage__heading span')).toBeHidden()
  await expect(answerInput).toBeEnabled()
  await answerInput.fill('SLIK')
  await page.getByRole('button', { name: 'Decode', exact: true }).click()
  await expect(page.locator('.alert--ok')).toContainText('Correct')
  await expect(score).toHaveText('0/110')

  await page.getByRole('button', { name: 'Next →' }).click()
  await page.clock.runFor(15_100)
  await expect(page.locator('.alert--error')).toContainText('Time ran out')
  await expect(score).toHaveText('-10/110')

  await page.getByRole('button', { name: 'Next →' }).click()
  await expect(page.locator('.qa-stage__heading span')).toBeHidden()
  await expect(answerInput).toBeEnabled()
  await expect(page.getByRole('timer', { name: '15 seconds remaining' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(answerInput).toBeVisible()
  const header = await page.locator('.qa-stage__header').boundingBox()
  expect(header?.height).toBeLessThan(150)
  const clue = await page.locator('.qa-stage__question').boundingBox()
  expect(clue?.y).toBeGreaterThan((header?.y ?? 0) + (header?.height ?? 0))
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/image-decode-mobile.png', fullPage: true })
})

test('a passed Image Decode timeout applies the wrong-answer penalty to both teams', async ({ page, context }) => {
  await page.goto('/admin')
  for (const name of ['Timeout Alpha', 'Timeout Beta']) {
    await page.getByRole('textbox', { name: 'New team name' }).fill(name)
    await page.getByRole('button', { name: 'Add team', exact: true }).click()
    await expect(page.getByText(name, { exact: true })).toBeVisible()
  }
  await page.goto('/admin/challenges')
  await page.locator('.card--locked', { hasText: 'Image Decode' }).getByRole('button', { name: 'Play', exact: true }).click()
  const time = new Date()
  await page.clock.install({ time })
  await page.clock.pauseAt(time)
  for (const checkbox of await page.locator('.run-panel__teams').getByRole('checkbox').all()) await checkbox.check()
  const popup = context.waitForEvent('page')
  await page.getByRole('button', { name: 'Start team run (2)' }).click()
  await popup
  await page.getByRole('radio', { name: 'Pass to an opponent' }).check()
  await page.getByRole('combobox', { name: 'Opponent team' }).selectOption({ index: 1 })
  await page.clock.runFor(16_000)
  await expect(page.locator('.run-panel__title')).toContainText('question 2 of 11')
  const scores = page.locator('.run-panel__answers tbody tr td:last-child')
  await expect(scores).toHaveText(['-5', '-5'])
})

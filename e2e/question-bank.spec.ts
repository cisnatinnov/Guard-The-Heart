import { test, expect } from '@playwright/test'
const matching = '/admin/play/word-assembly/7c4a2f96-08db-4e15-b3c7-1d9e5a80f463'
const jaw = '/admin/play/jaws-of-risk/d5e8b317-4c62-49af-8b03-2f7c19a6d5e8'

test('host manages shared questions and both challenges receive saved changes', async ({ page, context }) => {
  await page.goto('/admin/questions')
  await expect(page.getByRole('heading', { name: 'Question Bank', exact: true })).toBeVisible()
  await expect(page.getByText('69 questions', { exact: false })).toBeVisible()
  await page.getByLabel('Question bank', { exact: true }).selectOption('match-card')
  await expect(page.getByText('140 questions', { exact: false })).toBeVisible()
  await page.screenshot({ path: '.validation.tmp/question-bank-desktop.png', fullPage: true })
  const other = await context.newPage()
  await other.goto(jaw)
  await expect(other.locator('.workbook-quiz')).toBeVisible()
  await page.getByRole('button', { name: 'Add question', exact: true }).click()
  const form = page.getByRole('form', { name: 'Add question', exact: true })
  await form.getByLabel('Question', { exact: true }).fill('Shared question created by host')
  for (const [index, text] of ['Allow', 'Deny', 'Ignore', 'Wait'].entries()) await form.getByLabel(`Option ${String.fromCharCode(65 + index)}`, { exact: true }).fill(text)
  await form.getByLabel('Correct answer', { exact: true }).selectOption('Deny')
  await form.getByLabel('Explanation', { exact: true }).fill('Use the approved process.')
  await form.getByRole('button', { name: 'Save question', exact: true }).click()
  await expect(page.getByRole('status')).toHaveText('Question added.')
  // The already open challenge receives the changed bank across tabs.
  await other.locator('.question-picker > summary').click()
  await expect(other.locator('.question-picker')).toContainText('Shared question created by host')
  await other.goto(matching)
  await other.locator('.question-picker > summary').click()
  await expect(other.locator('.question-picker')).toContainText('Shared question created by host')
  await other.getByRole('button', { name: 'Clear selection', exact: true }).click()
  await other.getByRole('checkbox', { name: /Shared question created by host/ }).check()
  await expect(other.locator('.workbook-quiz > h2')).toHaveText('Shared question created by host')
  await expect(other.locator('.quiz-option span')).toHaveText(['Allow', 'Deny', 'Ignore', 'Wait'])
  await page.getByLabel('Search questions').fill('Shared question created by host')
  await page.locator('.question-bank__item').getByRole('button', { name: 'Edit', exact: true }).click()
  await page.getByRole('form', { name: 'Edit question' }).getByLabel('Question', { exact: true }).fill('Edited shared question')
  await page.getByRole('button', { name: 'Save question', exact: true }).click()
  await page.getByLabel('Search questions').fill('Edited shared question')
  await page.reload()
  await page.getByLabel('Question bank', { exact: true }).selectOption('match-card')
  await page.getByLabel('Search questions').fill('Edited shared question')
  await expect(page.locator('.question-bank__item')).toContainText('Use the approved process.')
  await page.getByRole('button', { name: 'Delete', exact: true }).click()
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click()
  await expect(page.locator('.question-bank__item')).toHaveCount(0)
  await page.reload()
  await page.getByLabel('Question bank', { exact: true }).selectOption('match-card')
  await page.getByLabel('Search questions').fill('Edited shared question')
  await expect(page.locator('.question-bank__item')).toHaveCount(0)
})


import { expect, test } from '@playwright/test'
const decode = '/admin/play/emoji-decode/9f1c3a52-0d64-4e2b-8a71-5c0e2b7d4a10'
const matching = '/admin/play/word-assembly/7c4a2f96-08db-4e15-b3c7-1d9e5a80f463'

test('dark default, persistent theme switch, and unclipped narrow navigation', async ({ page, context }) => {
  await page.goto('/admin')
  await expect(page.getByRole('heading', { name: 'Teams', exact: true })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('.app--admin')).toHaveCSS('color-scheme','dark')
  const secondHost = await context.newPage()
  await secondHost.goto('/admin/timer')
  await page.getByRole('button', { name: 'Dark theme', exact: true }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await expect(secondHost.getByRole('button',{name:'Dark theme',exact:true})).toHaveText('Dark theme')
  await expect(secondHost.locator('.app--admin')).toHaveCSS('color-scheme','light')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.setViewportSize({ width: 357, height: 760 })
  const nav = page.getByRole('navigation', { name: 'Admin views' })
  await expect(nav.getByRole('link')).toHaveCount(12)
  expect(await nav.evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: '.validation.tmp/admin-mobile.png', fullPage: true })
})

test('Image Decode reminder does not score or close answers', async ({ page }) => {
  await page.goto(decode)
  await page.clock.install()
  await page.getByRole('checkbox', { name: 'Kuning', exact: true }).check()
  await page.getByRole('button', { name: 'Start team run (1)', exact: true }).click()
  await page.clock.runFor(16000)
  await expect(page.locator('.qa-stage__timer strong')).toHaveText('0s')
  const answer = page.getByRole('textbox', { name: 'Kuning answer', exact: true })
  await expect(answer).toBeEnabled()
  await expect(page.locator('.run-panel__answers tbody tr td:last-child')).toHaveText('0')
  await answer.fill('Selisih Kas')
  await page.getByRole('button', { name: 'Grade this question', exact: true }).click()
  await expect(page.locator('.run-panel__answers tbody tr td:last-child')).toHaveText('10')
})

test('Turn Order selects the Image Decode team live and persists across reload', async ({ page, context }) => {
  await page.goto('/admin/turn-order')
  await expect(page.locator('.turn-order-item button')).toHaveCount(5)
  const orderPage = page
  const game = await context.newPage()
  await game.goto(decode)
  for (const name of ['Kuning', 'Merah']) await game.getByRole('checkbox', { name, exact: true }).check()
  await orderPage.locator('.turn-order-item button').filter({ hasText: 'Merah' }).click()
  await game.getByRole('button', { name: 'Start team run (2)', exact: true }).click()
  await expect(game.locator('.run-panel__header')).toContainText('Merah answers this question.')
  await orderPage.locator('.turn-order-item button').filter({ hasText: 'Kuning' }).click()
  await expect(game.locator('.run-panel__header')).toContainText('Kuning answers this question.')
  await game.clock.install()
  await game.clock.fastForward(16000)
  await expect(game.getByRole('textbox', { name: 'Kuning answer', exact: true })).toBeEnabled()
  await game.reload()
  await expect(game.locator('.run-panel__header')).toContainText('Kuning answers this question.')
  await game.screenshot({ path: '.validation.tmp/decode-dark.png', fullPage: true })
  await game.getByRole('textbox', { name: 'Kuning answer', exact: true }).fill('Selisih Kas')
  await game.getByRole('button', { name: 'Grade this question', exact: true }).click()
  await expect(game.locator('.run-panel__title')).toContainText('question 2 of 10')
  await expect(orderPage.locator('.turn-order-item[aria-current]')).toContainText('Merah')
})

test('workbook quizzes sync question and answer reveal to the public view without timers', async ({ page, context }) => {
  await page.goto(matching)
  const quiz = page.getByRole('region', { name: 'Workbook question' })
  await expect(quiz).toContainText('HP kamu tiba-tiba')
  await expect(quiz.locator('.workbook-quiz__options li')).toHaveCount(4)
  const publicPage = await context.newPage()
  await publicPage.goto(matching.replace('/admin', ''))
  await page.getByRole('button', { name: 'Reveal answer', exact: true }).click()
  await expect(publicPage.locator('.workbook-quiz__answer')).toContainText('Tolak (Deny)')
  await page.getByRole('button', { name: 'Next question', exact: true }).click()
  await expect(publicPage.locator('.workbook-quiz h2')).toContainText('IT Support')
  await expect(publicPage.getByRole('timer')).toHaveCount(0)
  await page.goto('/admin/play/jaws-of-risk/d5e8b317-4c62-49af-8b03-2f7c19a6d5e8')
  await expect(page.locator('.workbook-quiz h2')).toContainText('platform AI gratis')
  await expect(page.getByRole('timer')).toHaveCount(0)
})

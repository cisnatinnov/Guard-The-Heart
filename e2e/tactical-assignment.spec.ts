import { expect, test } from '@playwright/test'
import initSqlJs from 'sql.js'
import { resolve } from 'node:path'

test('Protect and Thief support clicking and direct drops while keeping ownership', async ({ page }) => {
  await page.setViewportSize({width:1440,height:2400})
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  const challengeId = '9f1c3a52-0d64-4e2b-8a71-5c0e2b7d4a10'
  const SQL = await initSqlJs({ locateFile: (file) => resolve('node_modules/sql.js/dist', file) })
  await page.goto(`/admin/tactical/${challengeId}`)
  await expect(page.getByRole('button', { name:'Skip Biru', exact:true })).toBeVisible()
  const read = () => page.evaluate(() => new Promise<number[]>((accept, reject) => {
    const open = indexedDB.open('guard-the-heart', 1)
    open.onerror = () => reject(open.error)
    open.onsuccess = () => {
      const db = open.result, tx = db.transaction('sqlite', 'readonly'), get = tx.objectStore('sqlite').get('database')
      get.onsuccess = () => accept(Array.from(new Uint8Array(get.result ?? [])))
      get.onerror = () => reject(get.error)
      tx.oncomplete = () => db.close()
    }
  }))
  await expect.poll(async () => {
    const bytes = await read()
    if (!bytes.length) return 0
    const db = new SQL.Database(new Uint8Array(bytes))
    const count = Number(db.exec('SELECT COUNT(*) FROM card')[0].values[0][0])
    db.close()
    return count
  }).toBe(60)
  const db = new SQL.Database(new Uint8Array(await read()))
  const ids = Object.fromEntries(['Merah','Biru','Kuning'].map((name) => [name,String(db.exec(`SELECT id FROM team WHERE name='${name}'`)[0].values[0][0])]))
  for (const [id,name] of [['protect','Rare Protect Card #01'],['thief','Normal Thief Card #01'],['epic','Epic Thief Card #01']]) {
    db.run('UPDATE card SET team=?,challenge=? WHERE name=?',[ids.Merah,challengeId,name])
    db.run('INSERT INTO team_card (id,name,type,effect,effect_action,icon,team,challenge_point,createdAt,updatedAt) SELECT ?,name,type,effect,effect_action,icon,team,challenge_point,createdAt,updatedAt FROM card WHERE name=?',[id,name])
  }
  const bytes = Array.from(db.export())
  db.close()
  await page.evaluate((bytes) => new Promise<void>((accept, reject) => {
    const open = indexedDB.open('guard-the-heart', 1)
    open.onerror = () => reject(open.error)
    open.onsuccess = () => {
      const db = open.result, tx = db.transaction('sqlite', 'readwrite')
      tx.objectStore('sqlite').put(new Uint8Array(bytes), 'database')
      tx.oncomplete = () => { db.close(); accept() }
      tx.onerror = () => reject(tx.error)
    }
  }), bytes)
  await page.reload()
  const owned = (name: string) => page.getByRole('button',{name:`Select ${name} Card #01 for Merah`,exact:true})
  const selection = (team: string) => page.getByLabel(`Selected cards for ${team}`,{exact:true})
  const assign = (card: string, team: string, slot = '') => page.getByRole('button',{name:`Assign ${card} Card #01 owned by Merah to ${team}${slot}`,exact:true})
  const protectTarget = (team: string) => assign('Rare Protect', team)
  await owned('Rare Protect').click()
  await assign('Rare Protect','Merah').click()
  await expect(protectTarget('Merah')).toHaveAttribute('aria-pressed', 'true')
  await assign('Rare Protect','Biru').click()
  await expect(protectTarget('Biru')).toHaveAttribute('aria-pressed', 'true')
  await owned('Rare Protect').dragTo(selection('Merah'))
  await expect(protectTarget('Merah')).toHaveAttribute('aria-pressed', 'true')
  await owned('Rare Protect').dragTo(selection('Biru'))
  await expect(protectTarget('Biru')).toHaveAttribute('aria-pressed', 'true')
  await expect(selection('Biru').getByRole('button')).toHaveCount(0)
  await expect(page.getByLabel('Assigned effects for Biru',{exact:true})).toContainText('Owner: Merah')
  await expect(page.getByLabel('Assigned effects for Merah',{exact:true})).toContainText('Protected by Rare Protect')
  await expect(page.locator('.giga-card-actions select')).toHaveCount(0)
  await owned('Normal Thief').dragTo(selection('Kuning'))
  await expect(page.locator('.tactical-admin__team-header h3').filter({hasText:'Tim Merah'})).toContainText('5 GP')
  await expect(page.locator('.tactical-admin__team-header h3').filter({hasText:'Tim Kuning'})).toContainText('5 GP')
  const thiefTarget = (team: string) => assign('Normal Thief', team)
  await expect(thiefTarget('Kuning')).toHaveAttribute('aria-pressed', 'true')
  await assign('Normal Thief','Biru').click()
  await expect(thiefTarget('Biru')).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.tactical-admin__team-header h3').filter({hasText:'Tim Kuning'})).toContainText('5 GP')
  await expect(page.locator('.tactical-admin__team-header h3').filter({hasText:'Tim Biru'})).toContainText('5 GP')
  await expect(assign('Normal Thief','Merah')).toHaveCount(0)
  await owned('Normal Thief').dragTo(selection('Merah'))
  await expect(page.getByRole('alert')).toContainText('opposing team')
  await expect(thiefTarget('Biru')).toHaveAttribute('aria-pressed', 'true')
  await owned('Normal Thief').click()
  await owned('Epic Thief').dragTo(selection('Biru'))
  await page.getByRole('button',{name:'Remove Epic Thief Card #01 from Merah',exact:true}).dragTo(selection('Kuning'))
  const epicTarget = (team: string, slot: number) => assign('Epic Thief', team, ` · ${slot}`)
  await expect(epicTarget('Biru', 1)).toHaveAttribute('aria-pressed', 'true')
  await expect(epicTarget('Kuning', 2)).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.tactical-admin__team-header h3').filter({hasText:'Tim Merah'})).toContainText('5 GP')
  await expect(assign('Epic Thief','Biru',' · 2')).toBeDisabled()
  await expect(selection('Merah').getByRole('button')).toHaveCount(2)
  await page.reload()
  await expect(protectTarget('Biru')).toHaveAttribute('aria-pressed', 'true')
  await expect(epicTarget('Kuning', 2)).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('.giga-card-actions select')).toHaveCount(0)
  const ownerPanel = page.locator('.tactical-admin__team').filter({ has: page.getByRole('heading', { name: /^Tim Merah / }) })
  await expect(ownerPanel.locator('.tactical-targets')).toHaveCount(3)
  await expect(page.locator('.giga-card-actions .tactical-targets')).toHaveCount(0)
  await expect(page.locator('.giga-card-actions')).toHaveCount(0)
  for (const width of [1366, 768, 390]) {
    await page.setViewportSize({width,height:900})
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true)
    const violations = await ownerPanel.evaluate((panel) => {
      const bounds = panel.getBoundingClientRect()
      return [...panel.querySelectorAll('.tactical-admin__target-card, .tactical-targets, .tactical-targets button')].filter((node) => {
        const box = node.getBoundingClientRect()
        return box.left < bounds.left || box.right > bounds.right || box.top < bounds.top || box.bottom > bounds.bottom
      }).length
    })
    expect(violations).toBe(0)
    await ownerPanel.screenshot({path:`test-results/tactical-targets-${width}.png`})
  }
  await page.setViewportSize({width:1440,height:2400})
  const leaderboard = await page.context().newPage()
  await leaderboard.goto('/leaderboard')
  const redStanding = leaderboard.locator('.ranking-table tbody tr').filter({ hasText: 'Tim Merah' })
  await expect(redStanding.locator('.ranking-effects')).not.toContainText('Dicuri')
  await expect(redStanding.locator('td').nth(5)).toContainText('5')
  await expect(redStanding.locator('.ranking-effects')).not.toContainText('Protect')
  await expect(redStanding.locator('td').last().locator('strong')).toHaveText('1')
  await page.getByRole('button',{name:'Card Reveal',exact:true}).click()
  await expect(assign('Rare Protect','Merah')).toBeDisabled()
  const projector = await page.context().newPage()
  await projector.goto(`/card-reveal/${challengeId}`)
  const protectLabel = projector.locator('.tactical-stage__card-target[data-card-id="protect"]')
  const thiefLabel = projector.locator('.tactical-stage__card-target[data-card-id="epic"]')
  await expect(protectLabel).toHaveText('Protect: Biru')
  await expect(thiefLabel).toHaveText('Thief: Biru, Kuning')
  await expect(protectLabel).toBeVisible()
  await expect(thiefLabel).toBeVisible()
  await projector.locator('.tactical-stage__played-card[data-card-id="epic"]').hover()
  await expect(projector.locator('.tactical-stage__log strong')).toHaveText('Thief')
  const redGP = projector.locator('.tactical-stage__team').filter({ has: projector.getByRole('heading', { name: 'Tim Merah', exact: true }) }).locator('.tactical-stage__gp')
  await expect(redGP).toHaveAttribute('data-gp-from', '5')
  await expect(redGP).toHaveAttribute('data-gp-to', '9')
  await expect(projector.locator('.tactical-stage__gp--down')).toHaveCount(2)
  await expect(redGP.locator('.tactical-stage__gp-number')).toHaveText('9 GP')
  expect(await projector.locator('.tactical-stage__team').evaluateAll((elements) => elements.every((team) => {
    const bounds = team.getBoundingClientRect(), number = team.querySelector('.tactical-stage__gp-number')!.getBoundingClientRect()
    return number.top >= bounds.top && number.bottom <= bounds.bottom && number.left >= bounds.left && number.right <= bounds.right
  }))).toBe(true)
  await projector.screenshot({ path: 'test-results/card-reveal-hover-thief.png' })
  await projector.mouse.move(0, 0)
  await expect(projector.locator('.tactical-stage__gp-change')).toHaveCount(0)
  const sizes = await projector.locator('.tactical-stage__team').filter({hasText:'Tim Merah'}).locator('.tactical-stage__played-card .card-art img').evaluateAll((images)=>images.map((image)=>({y:image.getBoundingClientRect().y,height:image.getBoundingClientRect().height})))
  expect(Math.abs(sizes[0].height-sizes[1].height)).toBeLessThan(1)
  expect(Math.abs(sizes[0].y-sizes[1].y)).toBeLessThan(1)
  await projector.screenshot({ path:'test-results/card-reveal-targets.png' })
  await page.getByRole('button', { name:'Return to Tactical Phase', exact:true }).click()
  await expect(projector.locator('.tactical-stage__card-target')).toHaveCount(0)
  await page.getByRole('button', { name:'Serang semua tim −2 GP', exact:true }).click()
  await expect(page.getByRole('button', { name:'Serangan selesai', exact:true })).toBeDisabled()
  await expect(projector.locator('.tactical-stage__team').filter({hasText:'Tim Merah'}).locator('.tactical-stage__gp')).toContainText('9 GP')
  await expect(projector.locator('.tactical-stage__team').filter({hasText:'Tim Biru'}).locator('.tactical-stage__gp')).toContainText('3 GP')
  await expect(protectLabel).toHaveText('Protect: Biru')
  await expect(thiefLabel).toHaveText('Thief: Biru, Kuning')
  await projector.reload()
  await expect(protectLabel).toHaveText('Protect: Biru')
  await expect(thiefLabel).toHaveText('Thief: Biru, Kuning')
  expect(errors).toEqual([])
})

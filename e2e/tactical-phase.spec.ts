import { test, expect } from '@playwright/test'
test('public tactical cards are face-up, used cards disappear from both inventories while reveal history stays available', async ({ page, context }) => {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.setViewportSize({ width: 1280, height: 2400 })
  await page.goto('/admin')
  await page.goto('/admin/challenges')
  const id = '9f1c3a52-0d64-4e2b-8a71-5c0e2b7d4a10'
  await page.goto(`/admin/scoreboard/${id}`)
  for (const [index, name] of ['Merah', 'Biru', 'Kuning', 'Pink', 'Hijau'].entries()) {
    await page.locator('.grid-form select').selectOption({ label: name })
    await page.locator('.grid-form input[type="number"]').fill(String(50 - index * 10))
    await page.getByRole('button', { name: 'Add entry' }).click()
    await expect(page.locator('.board__row')).toHaveCount(index + 1)
  }
  const projector = await context.newPage()
  await projector.setViewportSize({ width: 1280, height: 720 })
  projector.on('pageerror', (error) => errors.push(error.message))
  await projector.goto(`/scoreboard/${id}`)
  await expect(projector.getByRole('list', { name: 'Challenge ranking' })).toContainText('Merah')
  await page.evaluate(() => {
    const rarities = [.65,.65,.65,.65,.65,0,.95,0]
    let roll = 0
    Math.random = () => roll < 16 ? (++roll % 2 ? rarities[(roll - 1) / 2] : .3) : .3
  })
  await page.getByRole('button', { name: 'Claim Rewards', exact: true }).click()
  await expect(page).toHaveURL(/\/admin\/rewards\//)
  await expect(projector).toHaveURL(/\/rewards\//)
  await expect(page.getByRole('listitem', { name: 'Merah', exact: true }).locator('.card-art img')).toHaveCount(3)
  const firstCards = await page.getByRole('listitem', { name: 'Merah', exact: true }).locator('.card-art img').evaluateAll((images) => images.map((image) => (image as HTMLImageElement).src))
  const secondId = 'd5e8b317-4c62-49af-8b03-2f7c19a6d5e8'
  await page.goto(`/admin/scoreboard/${secondId}`)
  for (const [index, name] of ['Merah', 'Biru', 'Kuning', 'Pink', 'Hijau'].entries()) {
    await page.locator('.grid-form select').selectOption({ label: name })
    await page.locator('.grid-form input[type="number"]').fill(String(50 - index * 10))
    await page.getByRole('button', { name: 'Add entry' }).click()
    await expect(page.locator('.board__row')).toHaveCount(index + 1)
  }
  await page.evaluate(() => { Math.random = () => 0 })
  await page.getByRole('button', { name: 'Claim Rewards', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/admin/rewards/${secondId}$`))
  await page.goto(`/admin/rewards/${id}`)
  await page.getByRole('button', { name: 'Tactical Phase', exact: true }).click()
  await expect(projector).toHaveURL(/\/tactical\//)
  const red = page.locator('.tactical-admin__team').filter({ has: page.getByRole('heading', { name: /Tim Merah/ }) })
  await expect(red.locator('.tactical-admin__cards button')).toHaveCount(6)
  expect(await red.locator('.tactical-admin__card-group').filter({ hasText: 'Current challenge' }).locator('img').evaluateAll((images) => images.map((image) => (image as HTMLImageElement).src))).toEqual(firstCards)
  await page.getByRole('combobox', { name: 'Challenge', exact: true }).selectOption(secondId)
  await expect(page).toHaveURL(new RegExp(`/admin/tactical/${secondId}$`))
  await expect(red.locator('.tactical-admin__cards button')).toHaveCount(6)
  expect(await red.locator('.tactical-admin__card-group').filter({ hasText: 'Current challenge' }).locator('img').evaluateAll((images) => images.map((image) => (image as HTMLImageElement).src))).not.toEqual(firstCards)
  await page.getByRole('combobox', { name: 'Challenge', exact: true }).selectOption(id)
  await expect(page).toHaveURL(new RegExp(`/admin/tactical/${id}$`))
  await expect(red.locator('.tactical-admin__cards button')).toHaveCount(6)
  await expect(projector.locator('.tactical-stage__team').filter({ hasText: 'Tim Merah' }).locator('.tactical-stage__collection img')).toHaveCount(6)
  await red.locator('.tactical-admin__cards button').nth(0).click()
  await expect(red.getByRole('button', {name:/^Select Normal Shield/})).toBeEnabled()
  await red.getByRole('button', {name:/^Select Normal Shield/}).dragTo(red.locator('.tactical-admin__selection'))
  await expect(red.locator('.tactical-admin__selection button')).toHaveCount(2)
  await page.screenshot({ path: 'test-results/tactical-admin-neat.png', fullPage: true })
  await red.getByRole('button', {name:/^Select Rare Heal/}).click()
  await expect(page.getByRole('alert')).toContainText('at most 2')
  const blue = page.locator('.tactical-admin__team').filter({ has: page.getByRole('heading', { name: /Tim Biru/ }) })
  await red.getByRole('button', {name:/^Select Rare Heal/}).dragTo(blue.locator('.tactical-admin__selection'))
  await expect(page.getByRole('alert')).toContainText('earned by this team')
  await page.getByRole('button', { name: 'Skip Hijau', exact: true }).click()
  await expect(projector.locator('.tactical-stage__team').filter({ hasText: 'Tim Merah' })).toContainText('2 Kartu siap')
  await expect(projector.locator('.tactical-stage__collection .card-art')).toHaveCount(16)
  await expect(projector.locator('.tactical-stage__selected .card-art')).toHaveCount(2)
  await expect(projector.getByRole('button')).toHaveCount(0)
  await projector.screenshot({ path: 'test-results/tactical-slide-05-public.png' })
  await projector.goto(`/card-reveal/${id}`)
  await expect(projector.getByRole('heading', { name: 'Card Reveal', exact: true })).toBeAttached()
  await expect(projector.locator('.card-art')).toHaveCount(0)
  await expect(projector.locator('.tactical-stage__log')).toContainText('Kartu belum dibuka')
  await projector.goto(`/tactical/${id}`)
  await expect(projector.locator('.tactical-stage__team').filter({ hasText: 'Tim Merah' })).toContainText('2 Kartu siap')
  await page.reload()
  await expect(red.locator('.tactical-admin__selection button')).toHaveCount(2)
  await page.getByRole('button', { name: 'Card Reveal', exact: true }).click()
  expect(context.pages()).toHaveLength(2)
  await expect(page).toHaveURL(new RegExp(`/admin/tactical/${id}$`))
  await expect(projector).toHaveURL(/\/card-reveal\//)
  await expect(projector.locator('.card-art')).toHaveCount(2)
  await expect(projector.locator('.tactical-stage__team').filter({ hasText: 'Tim Merah' })).toContainText('Pakai 2 Kartu')
  await expect(projector.locator('.tactical-stage__status').filter({ hasText: 'SKIP' })).toHaveCount(4)
  await projector.reload()
  await expect(projector.locator('.card-art')).toHaveCount(2)
  await projector.screenshot({ path: 'test-results/card-reveal-slide-06-public.png' })
  await page.getByRole('button', { name: 'Return to Tactical Phase', exact: true }).click()
  await expect(projector).toHaveURL(/\/tactical\//)
  for (const name of ['Merah', 'Biru', 'Kuning', 'Pink', 'Hijau']) await page.getByRole('button', { name: `Skip ${name}`, exact: true }).click()
  await page.getByRole('button', { name: 'Card Reveal', exact: true }).click()
  await expect(projector).toHaveURL(/\/card-reveal\//)
  await expect(projector.locator('.card-art')).toHaveCount(0)
  await expect(projector.locator('.tactical-stage__log')).toHaveText('Semua tim memilih SKIP')
  await page.getByRole('button', { name: 'Return to Tactical Phase', exact: true }).click()
  await red.locator('.tactical-admin__cards button').first().click()
  const targets = page.getByRole('combobox', { name: /^Target / })
  for (const target of await targets.all()) await target.selectOption(await target.locator('option:not(:disabled)').filter({hasNotText:'Pilih tim lawan'}).first().getAttribute('value') ?? '')
  await page.getByRole('button', { name: 'Serang semua tim −2 GP', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Serangan selesai', exact: true })).toBeDisabled()
  await expect(projector).toHaveURL(new RegExp(`/card-reveal/${id}$`))
  await expect(projector.locator('.tactical-stage--resolved .card-art')).toHaveCount(1)
  await expect(projector.locator('.tactical-stage--resolved .card-art')).toHaveCSS('animation-name', 'tactical-card-use')
  await expect(red.locator('.tactical-admin__owned-card.is-used')).toHaveCount(0)
  await expect(red.locator('.tactical-admin__cards button')).toHaveCount(5)
  await expect(red.locator('.tactical-admin__selection button')).toHaveCount(1)
  await expect(red.locator('.tactical-admin__selection button')).toBeDisabled()
  await page.getByRole('combobox', { name: 'Challenge', exact: true }).selectOption(secondId)
  await expect(red.locator('.tactical-admin__cards button')).toHaveCount(5)
  await expect(red.locator('.tactical-admin__owned-card.is-used button')).toHaveCount(0)
  await page.getByRole('combobox', { name: 'Challenge', exact: true }).selectOption(id)
  await expect(red.locator('.tactical-admin__selection button')).toHaveCount(1)
  await page.reload()
  await expect(red.locator('.tactical-admin__selection button')).toBeDisabled()
  await expect(red.locator('.tactical-admin__cards button')).toHaveCount(5)
  await expect(projector.locator('.tactical-stage__selected .card-art')).toHaveCount(1)
  await page.getByRole('combobox', { name: 'Challenge', exact: true }).selectOption(secondId)
  await red.locator('.tactical-admin__card-group').filter({ hasNotText: 'Current challenge' }).locator('button:enabled').first().click()
  await expect(red.locator('.tactical-admin__selection button')).toHaveCount(1)
  await page.screenshot({ path: 'test-results/tactical-card-history.png', fullPage: true })
  await expect(projector.locator('.tactical-stage__selected .card-art')).toHaveCount(1)
  const publicOwned = projector.getByLabel('Owned cards for Merah', { exact: true })
  await expect(publicOwned.locator('img')).toHaveCount(5)
  await expect(publicOwned.locator('.tactical-stage__owned-used .card-art')).toHaveCount(0)
  await expect(publicOwned.locator('.tactical-stage__slot:not(.tactical-stage__owned-used) .card-art')).toHaveCount(5)
  await expect(publicOwned.locator('.tactical-stage__card-group')).toHaveCount(0)
  expect(errors).toEqual([])
})
